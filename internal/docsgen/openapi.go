package docsgen

import (
	"fmt"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// EmitOpenAPI builds an OpenAPI 3.0 document from scraped operations.
func EmitOpenAPI(ops []Operation, title string) ([]byte, error) {
	if title == "" {
		title = "Affise API"
	}

	byPath := map[string][]Operation{}
	for _, op := range ops {
		byPath[op.Path] = append(byPath[op.Path], op)
	}
	pathKeys := make([]string, 0, len(byPath))
	for k := range byPath {
		pathKeys = append(pathKeys, k)
	}
	sort.Strings(pathKeys)

	paths := &yaml.Node{Kind: yaml.MappingNode}
	for _, path := range pathKeys {
		methods := byPath[path]
		sort.Slice(methods, func(i, j int) bool {
			return methods[i].Method < methods[j].Method
		})
		item := &yaml.Node{Kind: yaml.MappingNode}
		for _, op := range methods {
			item.Content = append(item.Content,
				scalar(strings.ToLower(op.Method)),
				mustYAMLNode(operationObject(op)),
			)
		}
		paths.Content = append(paths.Content, scalar(path), item)
	}

	doc := &yaml.Node{Kind: yaml.MappingNode}
	appendKV(doc, "openapi", scalar("3.0.3"))
	appendKV(doc, "info", mustYAMLNode(map[string]any{
		"title":       title,
		"version":     "3.1-scraped",
		"description": "GENERATED from Affise HTML docs — DO NOT EDIT. Patch via openapi/overlays.yaml.",
	}))
	appendKV(doc, "servers", mustYAMLNode([]any{
		map[string]any{
			"url": "https://{host}",
			"variables": map[string]any{
				"host": map[string]any{"default": "api.affise.com"},
			},
		},
	}))
	appendKV(doc, "security", mustYAMLNode([]any{
		map[string]any{"ApiKeyAuth": []any{}},
	}))
	appendKV(doc, "paths", paths)
	appendKV(doc, "components", mustYAMLNode(map[string]any{
		"securitySchemes": map[string]any{
			"ApiKeyAuth": map[string]any{
				"type": "apiKey",
				"in":   "header",
				"name": "API-Key",
			},
		},
		"schemas": map[string]any{
			"AffiseObject": map[string]any{
				"type":                 "object",
				"additionalProperties": true,
			},
		},
	}))

	out, err := yaml.Marshal(doc)
	if err != nil {
		return nil, err
	}
	header := "# Code generated by affise-gen from Affise HTML docs. DO NOT EDIT.\n" +
		"# Fix docs↔API drift in openapi/overlays.yaml instead.\n"
	return append([]byte(header), out...), nil
}

func scalar(v string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
}

func appendKV(m *yaml.Node, key string, val *yaml.Node) {
	m.Content = append(m.Content, scalar(key), val)
}

func operationObject(op Operation) map[string]any {
	opID := operationID(op.Method, op.Path)
	params := make([]any, 0, len(op.Parameters))
	for _, p := range op.Parameters {
		params = append(params, parameterObject(p))
	}
	summary := op.Summary
	if summary == "" {
		summary = op.Method + " " + op.Path
	}
	return map[string]any{
		"operationId": opID,
		"summary":     summary,
		"parameters":  params,
		"responses": map[string]any{
			"200": map[string]any{
				"description": "Successful response",
				"content": map[string]any{
					"application/json": map[string]any{
						"schema": map[string]any{
							"$ref": "#/components/schemas/AffiseObject",
						},
					},
				},
			},
		},
	}
}

func parameterObject(p Parameter) map[string]any {
	typ, format, itemsType := MapAffiseType(p.Type)
	schema := map[string]any{"type": typ}
	if format != "" {
		schema["format"] = format
	}
	if typ == "array" {
		itemType := itemsType
		if itemType == "" {
			itemType = "string"
		}
		schema["items"] = map[string]any{"type": itemType}
	}
	if len(p.Enum) > 0 && typ == "string" {
		enums := make([]any, len(p.Enum))
		for i, e := range p.Enum {
			enums[i] = e
		}
		schema["enum"] = enums
	}
	if p.Default != "" {
		schema["default"] = coerceDefault(p.Default, typ)
	}
	return map[string]any{
		"name":        p.Name,
		"in":          p.In,
		"required":    p.Required || p.In == "path",
		"description": p.Description,
		"schema":      schema,
	}
}

func coerceDefault(v, typ string) any {
	v = strings.TrimSpace(v)
	switch typ {
	case "integer":
		var n int64
		if _, err := fmt.Sscan(v, &n); err == nil {
			return n
		}
	case "boolean":
		if strings.EqualFold(v, "true") {
			return true
		}
		if strings.EqualFold(v, "false") {
			return false
		}
	}
	return v
}

func operationID(method, path string) string {
	parts := strings.Split(strings.Trim(path, "/"), "/")
	var b strings.Builder
	b.WriteString(strings.ToLower(method))
	for _, p := range parts {
		p = strings.TrimPrefix(p, "{")
		p = strings.TrimSuffix(p, "}")
		if p == "" {
			continue
		}
		b.WriteString("_")
		for _, r := range p {
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
				b.WriteRune(r)
			} else {
				b.WriteRune('_')
			}
		}
	}
	return b.String()
}

func mustYAMLNode(v any) *yaml.Node {
	var n yaml.Node
	b, err := yaml.Marshal(v)
	if err != nil {
		panic(err)
	}
	if err := yaml.Unmarshal(b, &n); err != nil {
		panic(err)
	}
	if n.Kind == yaml.DocumentNode && len(n.Content) > 0 {
		return n.Content[0]
	}
	return &n
}
