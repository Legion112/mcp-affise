package docsgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/ohler55/ojg/jp"
	"github.com/ohler55/ojg/oj"
	"gopkg.in/yaml.v3"
)

// Overlay is an OpenAPI Overlay 1.0-style document.
type Overlay struct {
	Overlay string          `yaml:"overlay" json:"overlay"`
	Info    map[string]any  `yaml:"info" json:"info"`
	Actions []OverlayAction `yaml:"actions" json:"actions"`
}

// OverlayAction is one JSONPath update or remove.
type OverlayAction struct {
	Target      string `yaml:"target" json:"target"`
	Update      any    `yaml:"update,omitempty" json:"update,omitempty"`
	Remove      bool   `yaml:"remove,omitempty" json:"remove,omitempty"`
	Description string `yaml:"description,omitempty" json:"description,omitempty"`
}

// LoadOverlay reads an overlay YAML file. Missing file yields empty overlay.
func LoadOverlay(path string) (*Overlay, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return &Overlay{Overlay: "1.0.0", Actions: nil}, nil
		}
		return nil, err
	}
	var o Overlay
	if err := yaml.Unmarshal(data, &o); err != nil {
		return nil, fmt.Errorf("parse overlay %s: %w", path, err)
	}
	if o.Overlay == "" {
		o.Overlay = "1.0.0"
	}
	return &o, nil
}

// ApplyOverlay merges overlay actions onto an OpenAPI YAML document.
// Returns final YAML. Fails if any action target matches zero nodes.
func ApplyOverlay(openAPIYAML []byte, overlay *Overlay) ([]byte, error) {
	if overlay == nil || len(overlay.Actions) == 0 {
		if bytes.HasPrefix(bytes.TrimSpace(openAPIYAML), []byte("#")) {
			return openAPIYAML, nil
		}
		header := "# Code generated by affise-gen. DO NOT EDIT.\n"
		return append([]byte(header), openAPIYAML...), nil
	}

	var root any
	if err := yaml.Unmarshal(openAPIYAML, &root); err != nil {
		return nil, fmt.Errorf("decode openapi yaml: %w", err)
	}
	root = convertMapKeys(root)

	raw, err := json.Marshal(root)
	if err != nil {
		return nil, err
	}
	doc, err := oj.Parse(raw)
	if err != nil {
		return nil, fmt.Errorf("oj parse: %w", err)
	}

	for i, act := range overlay.Actions {
		if strings.TrimSpace(act.Target) == "" {
			return nil, fmt.Errorf("overlay action[%d]: empty target", i)
		}
		x, err := jp.ParseString(act.Target)
		if err != nil {
			return nil, fmt.Errorf("overlay action[%d] target %q: %w", i, act.Target, err)
		}
		nodes := x.Get(doc)
		if len(nodes) == 0 {
			return nil, fmt.Errorf("overlay action[%d]: target %q matched 0 nodes (stale overlay?)", i, act.Target)
		}
		if act.Remove {
			if err := x.Del(doc); err != nil {
				return nil, fmt.Errorf("overlay action[%d] remove %q: %w", i, act.Target, err)
			}
			continue
		}
		if act.Update == nil {
			return nil, fmt.Errorf("overlay action[%d]: need update or remove", i)
		}
		updateVal := normalizeUpdate(act.Update)
		if len(nodes) == 1 {
			merged := deepMerge(nodes[0], updateVal)
			if err := x.Set(doc, merged); err != nil {
				return nil, fmt.Errorf("overlay action[%d] update %q: %w", i, act.Target, err)
			}
			continue
		}
		// Multiple matches: merge update into each; ojg Set replaces all with one value,
		// so only support identical merge results or require single-match targets.
		merged := deepMerge(nodes[0], updateVal)
		for _, n := range nodes[1:] {
			if !jsonEqual(deepMerge(n, updateVal), merged) {
				return nil, fmt.Errorf("overlay action[%d] target %q matched %d nodes with divergent merges; narrow the JSONPath", i, act.Target, len(nodes))
			}
		}
		if err := x.Set(doc, merged); err != nil {
			return nil, fmt.Errorf("overlay action[%d] update %q: %w", i, act.Target, err)
		}
	}

	outYAML, err := yaml.Marshal(doc)
	if err != nil {
		return nil, err
	}
	header := "# Code generated by affise-gen (HTML docs ⊕ overlays). DO NOT EDIT.\n" +
		"# Edit openapi/overlays.yaml to correct docs↔API drift.\n"
	return append([]byte(header), outYAML...), nil
}

func normalizeUpdate(v any) any {
	b, err := json.Marshal(convertMapKeys(v))
	if err != nil {
		return v
	}
	parsed, err := oj.Parse(b)
	if err != nil {
		return v
	}
	return parsed
}

func convertMapKeys(v any) any {
	switch m := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(m))
		for k, val := range m {
			out[k] = convertMapKeys(val)
		}
		return out
	case map[any]any:
		out := make(map[string]any, len(m))
		for k, val := range m {
			out[fmt.Sprint(k)] = convertMapKeys(val)
		}
		return out
	case []any:
		out := make([]any, len(m))
		for i, val := range m {
			out[i] = convertMapKeys(val)
		}
		return out
	default:
		return v
	}
}

func deepMerge(dst, src any) any {
	dstMap, dstOK := asMap(dst)
	srcMap, srcOK := asMap(src)
	if !dstOK || !srcOK {
		return src
	}
	out := make(map[string]any, len(dstMap)+len(srcMap))
	for k, v := range dstMap {
		out[k] = v
	}
	for k, sv := range srcMap {
		if dv, ok := out[k]; ok {
			out[k] = deepMerge(dv, sv)
		} else {
			out[k] = sv
		}
	}
	return out
}

func asMap(v any) (map[string]any, bool) {
	switch m := v.(type) {
	case map[string]any:
		return m, true
	default:
		return nil, false
	}
}

func jsonEqual(a, b any) bool {
	ab, err := json.Marshal(a)
	if err != nil {
		return false
	}
	bb, err := json.Marshal(b)
	if err != nil {
		return false
	}
	return bytes.Equal(ab, bb)
}
